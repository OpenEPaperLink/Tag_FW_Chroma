#!/usr/bin/env python3
"""Scale the side logo bitmaps (CloudTop, oepli, CloudBottom) in
common/bitmaps.h for displays less than 128 pixels high, and write
common/bitmaps_small.h.

usage: gen_small_logo.py [size]     (size: logo length, default 96)

Bitmap format: [W, H, data]: H rows of W bits, MSB first.  On the side logo
a row is a logical column and W the logo's length down the display.
The banner (oepli, lettering) is area averaged, the dithered clouds are
sampled nearest neighbour so their dot density stays the same.
"""
import os
import re
import sys

NAMES = ('CloudTop', 'oepli', 'CloudBottom')


def c_array(src, name):
    m = re.search(r'\b' + name + r'\[[^\]]*\]\s*=\s*\{(.*?)\};', src, re.S)
    body = re.sub(r'//[^\n]*', '', m.group(1))
    return [int(x, 0) for x in re.findall(r'0x[0-9a-fA-F]+|\b\d+\b', body)]


def unpack(b):
    W, H, d = b[0], b[1], b[2:]
    return W, H, [[(d[r * (W // 8) + i // 8] >> (7 - i % 8)) & 1 for i in range(W)]
                  for r in range(H)]


def scale(W, H, px, nW, area):
    f = W / nW
    nH = max(1, round(H / f))
    out = []
    for r in range(nH):
        row = []
        for i in range(nW):
            if area:
                r0, r1 = r * H / nH, (r + 1) * H / nH
                i0, i1 = i * f, (i + 1) * f
                tot = cov = 0.0
                for sr in range(int(r0), min(H, int(r1 + 0.999))):
                    for si in range(int(i0), min(W, int(i1 + 0.999))):
                        a = (min(r1, sr + 1) - max(r0, sr)) * (min(i1, si + 1) - max(i0, si))
                        tot += a
                        cov += a * px[sr][si]
                row.append(1 if cov / tot >= 0.5 else 0)
            else:
                row.append(px[min(H - 1, int((r + 0.5) * H / nH))][min(W - 1, int((i + 0.5) * f))])
        out.append(row)
    return nH, out


def pack(W, rows):
    d = []
    for row in rows:
        for i in range(0, W, 8):
            v = 0
            for b in range(8):
                v = v << 1 | row[i + b]
            d.append(v)
    return d


def main():
    fw = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..')
    nW = int(sys.argv[1]) if len(sys.argv) > 1 else 96
    src = open(os.path.join(fw, 'common/bitmaps.h')).read()
    out = ['// Generated by tools/gen_small_logo.py from the logo in',
           f'// bitmaps.h, scaled to {nW} pixels for displays < 128 pixels high.',
           '// Same format: width, height, then height rows of width bits.', '']
    for name in NAMES:
        W, H, px = unpack(c_array(src, name))
        nH, rows = scale(W, H, px, nW, area=(name == 'oepli'))
        d = pack(nW, rows)
        out.append(f'static const uint8_t __code {name}[] = {{')
        out.append(f'   {nW}, {nH},')
        for i in range(0, len(d), nW // 8):
            out.append('   ' + ', '.join(f'0x{x:02x}' for x in d[i:i + nW // 8]) + ',')
        out.append('};')
        out.append('')
    p = os.path.join(fw, 'common/bitmaps_small.h')
    open(p, 'w', newline='\n').write('\n'.join(out))
    print('wrote', os.path.normpath(p))


if __name__ == '__main__':
    main()
